func TestScopeImportsNoInternal(t *testing.T) {
	out, err := exec.Command("go", "list", "-deps", "github.com/gopaytech/pergent/scope").Output()
	if err != nil {
		t.Fatalf("go list: %v", err)
	}
	for _, dep := range strings.Fields(string(out)) {
		if strings.Contains(dep, "/internal/") {
			t.Errorf("scope depends on %s", dep)
		}
	}
}

func TestPathRuleOrder(t *testing.T) {
	attrs := ParseAttributes([]byte("# comment\n\ngen/ linguist-generated\nx linguist-generated=true\ny linguist-vendored\nfoo/** -linguist-generated\n"))
	tests := []struct{ path, want string }{
		{"vendor/go.sum", "lockfile"}, // lockfile wins over vendored
		{"a/node_modules/x.js", "vendored"},
		{"third_party/x.c", "vendored"},
		{"web/package-lock.json", "lockfile"},
		{"gen/a.go", "generated"},
		{"sub/x", "generated"}, // "=true" form, basename pattern
		{"y", ""},              // linguist-vendored is not read
		{"foo/a.go", ""},       // unset attribute
		{"main.go", ""},
	}
	for _, tt := range tests {
		if got := attrs.PathRule(tt.path); got != tt.want {
			t.Errorf("PathRule(%q) = %q, want %q", tt.path, got, tt.want)
		}
	}
	var zero Attributes
	if got := zero.PathRule("main.go"); got != "" {
		t.Errorf("zero Attributes: PathRule = %q, want \"\"", got)
	}
}

// As in .gitattributes, the last matching line decides, and a line can unset
// the attribute (-attr, attr=false) or reset it to unspecified (!attr).
func TestPathRuleLastMatchWins(t *testing.T) {
	tests := []struct {
		name, attrs, path, want string
	}{
		{"unset after set", "gen/** linguist-generated\ngen/keep.go -linguist-generated\n", "gen/keep.go", ""},
		{"unset after set, other file stays", "gen/** linguist-generated\ngen/keep.go -linguist-generated\n", "gen/other.go", "generated"},
		{"=false after set", "gen/** linguist-generated\ngen/keep.go linguist-generated=false\n", "gen/keep.go", ""},
		{"reset after set", "gen/** linguist-generated\ngen/keep.go !linguist-generated\n", "gen/keep.go", ""},
		{"set again after unset", "*.go -linguist-generated\n*.go linguist-generated\n", "a.go", "generated"},
		{"=true after =false", "*.go linguist-generated=false\n*.go linguist-generated=true\n", "a.go", "generated"},
		{"last token on a line wins", "*.go linguist-generated -linguist-generated\n", "a.go", ""},
		{"last token on a line wins, set", "*.go -linguist-generated linguist-generated\n", "a.go", "generated"},
		{"unset line that does not match", "gen/** linguist-generated\nother/** -linguist-generated\n", "gen/a.go", "generated"},
		{"other attributes on the line", "gen/** -diff linguist-generated=false linguist-vendored\n", "gen/a.go", ""},
		{"macro line is not a pattern", "[attr]mine linguist-generated\n", "tmine", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := ParseAttributes([]byte(tt.attrs)).PathRule(tt.path); got != tt.want {
				t.Errorf("PathRule(%q) = %q, want %q", tt.path, got, tt.want)
			}
		})
	}
}

func TestDecide(t *testing.T) {
	tests := []struct {
		name           string
		paths, exclude []string
		p, rule        string
		optIn          bool
		want           string
	}{
		{"non-opt-in rule wins", []string{"*"}, nil, "a.png", "binary", false, "binary"},
		{"out of scope", []string{"*.go"}, nil, "a.py", "", false, "out of scope"},
		{"excluded by skill", nil, []string{"*_test.go"}, "a_test.go", "", false, "excluded by skill"},
		{"opt-in vendored, paths match", []string{"vendor/**"}, nil, "vendor/a.go", "vendored", true, ""},
		{"opt-in lockfile, no paths", nil, nil, "go.sum", "lockfile", true, "lockfile"},
		{"opt-in rule, paths do not match", []string{"*.go"}, nil, "x.lock", "lockfile", true, "out of scope"},
		{"exclude beats opt-in paths", []string{"vendor/**"}, []string{"*.go"}, "vendor/a.go", "vendored", true, "excluded by skill"},
		{"nothing", nil, nil, "main.go", "", false, ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := Decide(tt.paths, tt.exclude, tt.p, tt.rule, tt.optIn); got != tt.want {
				t.Errorf("Decide() = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestHasGeneratedHeader(t *testing.T) {
	tests := []struct {
		name, content string
		want          bool
	}{
		{"hash comment on line 1", "# Code generated by tool. DO NOT EDIT.\nkey: v\n", true},
		{"go comment, case-insensitive", "// CODE GENERATED by tool; do not edit.\npackage a\n", true},
		{"phrase inside a Go string", "package a\n\nvar s = \"code generated by x, do not edit\"\n", false},
		{"line 10 counts", strings.Repeat("x\n", 9) + "// Code generated by tool. DO NOT EDIT.\n", true},
		{"line 15 does not", strings.Repeat("x\n", 14) + "// Code generated by tool. DO NOT EDIT.\n", false},
		{"CRLF", "// Code generated by tool. DO NOT EDIT.\r\npackage a\r\n", true},
		{"empty", "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := HasGeneratedHeader(tt.content); got != tt.want {
				t.Errorf("HasGeneratedHeader() = %v, want %v", got, tt.want)
			}
		})
	}
}
