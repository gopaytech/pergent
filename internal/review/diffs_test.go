// diffWatch records the diff directory a review makes and the files it
// writes there, through the seams in diffs.go.
type diffWatch struct {
	mu       sync.Mutex
	dirs     []string
	writes   []string
	warnings []string
	// failMkdir makes the directory fail; failWrite fails the n-th write
	// (1-based) when positive.
	failMkdir bool
	failWrite int
}

// diffsWatched is set while a test watches the diffs; newRequest then leaves
// the seams alone.
var diffsWatched bool

// noDiffs makes the directory of diffs fail without a word, which leaves a
// review as it was before runs could read the diffs.
func noDiffs(t *testing.T) {
	t.Helper()
	oldMk, oldWarn := makeDiffDir, warnf
	t.Cleanup(func() { makeDiffDir, warnf = oldMk, oldWarn })
	makeDiffDir = func(string, string) (string, error) { return "", errors.New("diffs off in this test") }
	warnf = func(string, ...any) {}
}

func watchDiffs(t *testing.T) *diffWatch {
	t.Helper()
	w := &diffWatch{}
	oldMk, oldWrite, oldWarn := makeDiffDir, writeDiff, warnf
	diffsWatched = true
	t.Cleanup(func() { makeDiffDir, writeDiff, warnf = oldMk, oldWrite, oldWarn; diffsWatched = false })
	makeDiffDir = func(dir, pattern string) (string, error) {
		w.mu.Lock()
		defer w.mu.Unlock()
		if w.failMkdir {
			return "", errors.New("disk is full")
		}
		d, err := os.MkdirTemp(dir, pattern)
		w.dirs = append(w.dirs, d)
		return d, err
	}
	writeDiff = func(name string, data []byte, perm os.FileMode) error {
		w.mu.Lock()
		w.writes = append(w.writes, name)
		n := len(w.writes)
		w.mu.Unlock()
		if w.failWrite > 0 && n == w.failWrite {
			return errors.New("write failed")
		}
		return os.WriteFile(name, data, perm)
	}
	warnf = func(format string, args ...any) {
		w.mu.Lock()
		defer w.mu.Unlock()
		w.warnings = append(w.warnings, fmt.Sprintf(format, args...))
	}
	return w
}

const sectionHeading = "\n## Diffs of other changed files\n"

// section is the diff section of a changed-files.md: the list, then the
// diff file and the path of each line. ok is false when there is no section.
type sectionEntry struct{ file, path string }

func parseSection(t *testing.T, content string) (list string, entries []sectionEntry, ok bool) {
	t.Helper()
	list, rest, found := strings.Cut(content, sectionHeading)
	if !found {
		return content, nil, false
	}
	for _, l := range strings.Split(rest, "\n") {
		item, isItem := strings.CutPrefix(l, "- ")
		if !isItem {
			continue
		}
		file, path, cut := strings.Cut(item, ": ")
		if !cut {
			t.Fatalf("section line %q has no diff file", l)
		}
		entries = append(entries, sectionEntry{file, path})
	}
	return list, entries, true
}

func sectionPaths(entries []sectionEntry) []string {
	var out []string
	for _, e := range entries {
		out = append(out, e.path)
	}
	return out
}

func changedFilesOf(t *testing.T, c call) string {
	t.Helper()
	for i, p := range c.opts.Files {
		if filepath.Base(p) == "changed-files.md" {
			return c.contents[i]
		}
	}
	t.Fatalf("run %q has no changed-files.md among %q", c.opts.Message, c.opts.Files)
	return ""
}

func blockingOn(file string) finding.Finding {
	return finding.Finding{File: file, Line: 1, Severity: finding.Blocking, Title: "Bad", Explanation: "e"}
}

func quotedPatch(p, body string) string {
	a, b := strconv.Quote("a/"+p), strconv.Quote("b/"+p)
	return "diff --git " + a + " " + b + "\n--- " + a + "\n+++ " + b + "\n@@ -1 +1 @@\n-old\n+" + body + "\n"
}

const binaryPatch = "diff --git a/img.png b/img.png\nindex 1..2 100644\nBinary files a/img.png and b/img.png differ\n"

func eligibilityDiff() string {
	return strings.Join([]string{
		patch("lib/own.go", "x"),
		patch("cmd/normal.go", "n"),
		patch("go.sum", "x"),
		patch("vendor/v/v.go", "x"),
		patch("gen/g.go", "// Code generated by tool. DO NOT EDIT."),
		binaryPatch,
		deletedPatch("old/gone.go"),
		patch(".env", "SECRET=1"),
		patch("deploy/prod.env", "SECRET=2"),
		patch("deploy/app.env.local", "SECRET=3"),
		patch("deploy/.env.example", "SECRET=changeme"),
		patch("keys/id.pem", "KEY"),
		patch("keys/id.key", "KEY"),
		patch("infra/prod.tfvars", "pw"),
	}, "")
}

func TestDiffs_Eligibility(t *testing.T) {
	tests := []struct {
		name     string
		hardened bool
		want     []string
	}{
		// Without DenySecretFiles the config reads *.pem, *.key and *.tfvars,
		// so their diffs may be offered; with it they may not.
		{"secret files readable", false, []string{"cmd/normal.go", "deploy/.env.example", "keys/id.pem", "keys/id.key", "infra/prod.tfvars"}},
		{"secret files denied", true, []string{"cmd/normal.go", "deploy/.env.example"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			watchDiffs(t)
			f := &fake{respond: func(int, call) runner.RunResult { return completed(answer(t)) }}
			req := newRequest(t, f, eligibilityDiff(), skill.Skill{Name: "s", Body: "Review it.", Paths: []string{"lib/**"}})
			if tt.hardened {
				t.Setenv("OPENCODE_PROVIDER", "anthropic")
				t.Setenv("OPENCODE_MODEL", "test-model")
				req.Sandbox = Sandbox{Hardened: true}
			}

			Run(context.Background(), req)
			if len(f.calls) != 1 {
				t.Fatalf("runner called %d times, want 1", len(f.calls))
			}
			_, entries, ok := parseSection(t, changedFilesOf(t, f.calls[0]))
			if !ok {
				t.Fatalf("changed-files.md has no diff section: %q", f.calls[0].contents)
			}
			if got := sectionPaths(entries); !slices.Equal(got, tt.want) {
				t.Errorf("section lists %q, want %q", got, tt.want)
			}
		})
	}
}

func TestDiffs_ContentIsThePatchAndMappingPointsAtFiles(t *testing.T) {
	w := watchDiffs(t)
	var seen map[string]string
	f := &fake{}
	f.respond = func(_ int, c call) runner.RunResult {
		_, entries, _ := parseSection(t, changedFilesOf(t, c))
		seen = map[string]string{}
		for _, e := range entries {
			data, err := os.ReadFile(e.file)
			if err != nil {
				t.Errorf("diff file %s for %s: %v", e.file, e.path, err)
				continue
			}
			seen[e.path] = string(data)
			info, err := os.Stat(e.file)
			if err == nil && info.Mode().Perm() != 0600 {
				t.Errorf("diff file %s mode = %v, want 0600", e.file, info.Mode().Perm())
			}
			if filepath.Dir(e.file) != w.dirs[0] {
				t.Errorf("diff file %s is outside the diff directory %s", e.file, w.dirs[0])
			}
		}
		return completed(answer(t))
	}
	diffText := patch("a/one.go", "1") + patch("b/two.go", "2") + patch("c/three.go", "3")
	req := newRequest(t, f, diffText, skill.Skill{Name: "s", Body: "Review it.", Paths: []string{"a/**"}})

	Run(context.Background(), req)
	want := map[string]string{"b/two.go": patch("b/two.go", "2"), "c/three.go": patch("c/three.go", "3")}
	if len(seen) != len(want) {
		t.Fatalf("diff files = %v, want the two other files", seen)
	}
	for p, content := range want {
		if seen[p] != content {
			t.Errorf("diff file of %s = %q, want its patch %q", p, seen[p], content)
		}
	}
}

