package diff

import (
	"os"
	"path/filepath"
	"testing"
)

func patchWithHunk(path, added string) string {
	return "diff --git a/" + path + " b/" + path + "\nindex 1..2 100644\n--- a/" + path + "\n+++ b/" + path + "\n@@ -1 +1 @@\n-old\n+" + added + "\n"
}

func TestExclusion(t *testing.T) {
	repo := t.TempDir()
	attrs := "# comment\n\ngen/** linguist-generated\nother.txt text\nfoo/** -linguist-generated\nexplicit.pb linguist-generated=true\n"
	if err := os.WriteFile(filepath.Join(repo, ".gitattributes"), []byte(attrs), 0644); err != nil {
		t.Fatal(err)
	}
	c := NewClassifier(repo)

	tests := []struct {
		name     string
		f        FileDiff
		wantRule string
		wantOpt  bool
	}{
		{"deleted", FileDiff{Path: "a.go", Deleted: true, Patch: "diff --git a/a.go b/a.go\ndeleted file mode 100644\n@@ -1 +0,0 @@\n-x\n"}, "deleted", false},
		{"binary flag", FileDiff{Path: "a.png", Binary: true, Patch: "diff --git a/a.png b/a.png\nBinary files a/a.png and b/a.png differ\n"}, "binary", false},
		{"binary from patch text", FileDiff{Path: "a.png", Patch: "diff --git a/a.png b/a.png\nBinary files a/a.png and b/a.png differ\n"}, "binary", false},
		{"git binary patch text", FileDiff{Path: "a.bin", Patch: "diff --git a/a.bin b/a.bin\nGIT binary patch\nliteral 1\n"}, "binary", false},
		{"deleted wins over binary", FileDiff{Path: "a.png", Deleted: true, Binary: true, Patch: "x"}, "deleted", false},
		{"no content changes", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\nold mode 100644\nnew mode 100755\n"}, "no content changes", false},
		{"rename without hunks", FileDiff{Path: "n.yaml", OldPath: "o.yaml", Patch: "diff --git a/o.yaml b/n.yaml\nrename from o.yaml\nrename to n.yaml\n"}, "no content changes", false},
		{"lockfile", FileDiff{Path: "web/package-lock.json", Patch: patchWithHunk("web/package-lock.json", "x")}, "lockfile", true},
		{"go.sum", FileDiff{Path: "go.sum", Patch: patchWithHunk("go.sum", "x")}, "lockfile", true},
		{"vendored vendor", FileDiff{Path: "vendor/x/y.go", Patch: patchWithHunk("vendor/x/y.go", "x")}, "vendored", true},
		{"vendored node_modules", FileDiff{Path: "web/node_modules/x.js", Patch: patchWithHunk("web/node_modules/x.js", "x")}, "vendored", true},
		{"vendored third_party", FileDiff{Path: "third_party/x.c", Patch: patchWithHunk("third_party/x.c", "x")}, "vendored", true},
		{"generated by gitattributes", FileDiff{Path: "gen/a.go", Patch: patchWithHunk("gen/a.go", "x")}, "generated", true},
		{"generated by gitattributes =true", FileDiff{Path: "api/explicit.pb", Patch: patchWithHunk("api/explicit.pb", "x")}, "generated", true},
		{"generated by header", FileDiff{Path: "a.go", Patch: patchWithHunk("a.go", "// Code generated by tool. DO NOT EDIT.")}, "generated", true},
		{"unset attribute not generated", FileDiff{Path: "foo/a.go", Patch: patchWithHunk("foo/a.go", "x")}, "", false},
		{"header only in removed line", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1 +1 @@\n-// Code generated by tool. DO NOT EDIT.\n+x\n"}, "", false},
		{"plain go change", FileDiff{Path: "cmd/main.go", Patch: patchWithHunk("cmd/main.go", "x")}, "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rule, opt := c.Exclusion(tt.f)
			if rule != tt.wantRule || opt != tt.wantOpt {
				t.Errorf("Exclusion() = (%q, %v), want (%q, %v)", rule, opt, tt.wantRule, tt.wantOpt)
			}
		})
	}
}

func TestNewClassifier_NoGitattributes(t *testing.T) {
	c := NewClassifier(t.TempDir())
	f := FileDiff{Path: "gen/a.go", Patch: patchWithHunk("gen/a.go", "x")}
	if rule, _ := c.Exclusion(f); rule != "" {
		t.Errorf("rule = %q, want empty", rule)
	}
}

func TestEstimateTokens(t *testing.T) {
	tests := map[string]int{"": 0, "a": 1, "abcd": 1, "abcde": 2}
	for in, want := range tests {
		if got := EstimateTokens(in); got != want {
			t.Errorf("EstimateTokens(%q) = %d, want %d", in, got, want)
		}
	}
}
