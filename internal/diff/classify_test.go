func TestClassifierFrom_HeaderNeedsBase(t *testing.T) {
	f := FileDiff{Path: "n.go", Patch: "diff --git a/n.go b/n.go\n--- /dev/null\n+++ b/n.go\n@@ -0,0 +1,2 @@\n+// Code generated by tool. DO NOT EDIT.\n+package n\n"}

	var asked []string
	notAtBase := NewClassifierFrom(nil, func(p string) bool { asked = append(asked, p); return false })
	if rule, opt := notAtBase.Exclusion(f); rule != "" || opt {
		t.Errorf("header absent at base: Exclusion() = (%q, %v), want (\"\", false)", rule, opt)
	}
	if len(asked) != 1 || asked[0] != "n.go" {
		t.Errorf("generatedAtBase called with %v, want [n.go]", asked)
	}

	atBase := NewClassifierFrom(nil, func(string) bool { return true })
	if rule, opt := atBase.Exclusion(f); rule != "generated" || !opt {
		t.Errorf("header present at base: Exclusion() = (%q, %v), want (generated, true)", rule, opt)
	}

	// A file without the header never consults the base.
	called := false
	c := NewClassifierFrom(nil, func(string) bool { called = true; return true })
	if rule, _ := c.Exclusion(FileDiff{Path: "a.go", Patch: patchWithHunk("a.go", "x")}); rule != "" || called {
		t.Errorf("plain file: rule=%q called=%v, want \"\" and false", rule, called)
	}
}

func TestClassifierFrom_Gitattributes(t *testing.T) {
	f := FileDiff{Path: "gen/a.go", Patch: patchWithHunk("gen/a.go", "x")}

	c := NewClassifierFrom([]byte("# c\ngen/** linguist-generated\n"), func(string) bool { return false })
	if rule, opt := c.Exclusion(f); rule != "generated" || !opt {
		t.Errorf("Exclusion() = (%q, %v), want (generated, true)", rule, opt)
	}

	for _, empty := range [][]byte{nil, {}} {
		c := NewClassifierFrom(empty, nil)
		if rule, _ := c.Exclusion(f); rule != "" {
			t.Errorf("empty gitattributes: rule = %q, want \"\"", rule)
		}
	}
}

