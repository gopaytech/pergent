func patchWithHunk(path, added string) string {
	return "diff --git a/" + path + " b/" + path + "\nindex 1..2 100644\n--- a/" + path + "\n+++ b/" + path + "\n@@ -1 +1 @@\n-old\n+" + added + "\n"
}

func TestExclusion(t *testing.T) {
	repo := t.TempDir()
	attrs := "# comment\n\ngen/** linguist-generated\nother.txt text\nfoo/** -linguist-generated\nexplicit.pb linguist-generated=true\n"
	if err := os.WriteFile(filepath.Join(repo, ".gitattributes"), []byte(attrs), 0644); err != nil {
		t.Fatal(err)
	}
	c := NewClassifier(repo)

	tests := []struct {
		name     string
		f        FileDiff
		wantRule string
		wantOpt  bool
	}{
		{"deleted", FileDiff{Path: "a.go", Deleted: true, Patch: "diff --git a/a.go b/a.go\ndeleted file mode 100644\n@@ -1 +0,0 @@\n-x\n"}, "deleted", false},
		{"binary flag", FileDiff{Path: "a.png", Binary: true, Patch: "diff --git a/a.png b/a.png\nBinary files a/a.png and b/a.png differ\n"}, "binary", false},
		{"binary from patch text", FileDiff{Path: "a.png", Patch: "diff --git a/a.png b/a.png\nBinary files a/a.png and b/a.png differ\n"}, "binary", false},
		{"git binary patch text", FileDiff{Path: "a.bin", Patch: "diff --git a/a.bin b/a.bin\nGIT binary patch\nliteral 1\n"}, "binary", false},
		{"deleted wins over binary", FileDiff{Path: "a.png", Deleted: true, Binary: true, Patch: "x"}, "deleted", false},
		{"no content changes", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\nold mode 100644\nnew mode 100755\n"}, "no content changes", false},
		{"rename without hunks", FileDiff{Path: "n.yaml", OldPath: "o.yaml", Patch: "diff --git a/o.yaml b/n.yaml\nrename from o.yaml\nrename to n.yaml\n"}, "no content changes", false},
		{"lockfile", FileDiff{Path: "web/package-lock.json", Patch: patchWithHunk("web/package-lock.json", "x")}, "lockfile", true},
		{"go.sum", FileDiff{Path: "go.sum", Patch: patchWithHunk("go.sum", "x")}, "lockfile", true},
		{"vendored vendor", FileDiff{Path: "vendor/x/y.go", Patch: patchWithHunk("vendor/x/y.go", "x")}, "vendored", true},
		{"vendored node_modules", FileDiff{Path: "web/node_modules/x.js", Patch: patchWithHunk("web/node_modules/x.js", "x")}, "vendored", true},
		{"vendored third_party", FileDiff{Path: "third_party/x.c", Patch: patchWithHunk("third_party/x.c", "x")}, "vendored", true},
		{"generated by gitattributes", FileDiff{Path: "gen/a.go", Patch: patchWithHunk("gen/a.go", "x")}, "generated", true},
		{"generated by gitattributes =true", FileDiff{Path: "api/explicit.pb", Patch: patchWithHunk("api/explicit.pb", "x")}, "generated", true},
		{"generated by header", FileDiff{Path: "a.go", Patch: patchWithHunk("a.go", "// Code generated by tool. DO NOT EDIT.")}, "generated", true},
		{"generated hash comment header", FileDiff{Path: "a.yaml", Patch: patchWithHunk("a.yaml", "# Code generated by tool. DO NOT EDIT.")}, "generated", true},
		{"generated header in new file", FileDiff{Path: "n.go", Patch: "diff --git a/n.go b/n.go\nnew file mode 100644\n--- /dev/null\n+++ b/n.go\n@@ -0,0 +1,2 @@\n+// Code generated by tool. DO NOT EDIT.\n+package n\n"}, "generated", true},
		{"generated header as context line", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1,3 +1,3 @@\n // Code generated by tool. DO NOT EDIT.\n-old\n+new\n x\n"}, "generated", true},
		{"header phrase deep in file", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -118,3 +120,3 @@\n x\n-old\n+// Code generated by tool. DO NOT EDIT.\n"}, "", false},
		{"header phrase in hunk starting at +120", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -120 +120 @@\n-old\n+// Code generated by tool. DO NOT EDIT.\n"}, "", false},
		{"header phrase on 15th new line", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1,14 +1,15 @@\n" + strings.Repeat("+x\n", 14) + "+// Code generated by tool. DO NOT EDIT.\n"}, "", false},
		{"removed lines do not advance new side", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1,20 +1,2 @@\n" + strings.Repeat("-x\n", 15) + "+// Code generated by tool. DO NOT EDIT.\n"}, "generated", true},
		{"phrase in code, not after comment marker", FileDiff{Path: "a.go", Patch: patchWithHunk("a.go", `var re = regexp.MustCompile("code generated .*do not edit")`)}, "", false},
		{"unset attribute not generated", FileDiff{Path: "foo/a.go", Patch: patchWithHunk("foo/a.go", "x")}, "", false},
		{"header only in removed line", FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1 +1 @@\n-// Code generated by tool. DO NOT EDIT.\n+x\n"}, "", false},
		{"plain go change", FileDiff{Path: "cmd/main.go", Patch: patchWithHunk("cmd/main.go", "x")}, "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rule, opt := c.Exclusion(tt.f)
			if rule != tt.wantRule || opt != tt.wantOpt {
				t.Errorf("Exclusion() = (%q, %v), want (%q, %v)", rule, opt, tt.wantRule, tt.wantOpt)
			}
		})
	}
}

func TestExclusion_ReviewDeleted(t *testing.T) {
	repo := t.TempDir()
	if err := os.WriteFile(filepath.Join(repo, ".gitattributes"), []byte("gen/** linguist-generated\n"), 0644); err != nil {
		t.Fatal(err)
	}
	gen := "// Code generated by x. DO NOT EDIT."
	deletedWith := func(path, removed string) FileDiff {
		return FileDiff{Path: path, Deleted: true, Patch: "diff --git a/" + path + " b/" + path + "\ndeleted file mode 100644\nindex 1..0\n--- a/" + path + "\n+++ /dev/null\n@@ -1,2 +0,0 @@\n" + removed}
	}
	plain := deletedWith("a.go", "-package a\n-x\n")
	headerAt := func(line int) FileDiff {
		return deletedWith("a.go", strings.Repeat("-x\n", line-1)+"-"+gen+"\n")
	}

	on := NewClassifier(repo)
	on.ReviewDeleted = true
	onAtBaseFalse := NewClassifierFrom(nil, func(string) bool { return false })
	onAtBaseFalse.ReviewDeleted = true
	onAtBaseTrue := NewClassifierFrom(nil, func(string) bool { return true })
	onAtBaseTrue.ReviewDeleted = true
	off := NewClassifier(repo)

	tests := []struct {
		name     string
		c        Classifier
		f        FileDiff
		wantRule string
		wantOpt  bool
	}{
		{"text file", on, plain, "", false},
		{"binary flag", on, FileDiff{Path: "a.png", Deleted: true, Binary: true, Patch: "diff --git a/a.png b/a.png\ndeleted file mode 100644\nBinary files a/a.png and /dev/null differ\n"}, "deleted", false},
		{"binary from patch text", on, FileDiff{Path: "a.png", Deleted: true, Patch: "diff --git a/a.png b/a.png\ndeleted file mode 100644\nBinary files a/a.png and /dev/null differ\n"}, "deleted", false},
		{"empty file has no hunk", on, FileDiff{Path: "a.go", Deleted: true, Patch: "diff --git a/a.go b/a.go\ndeleted file mode 100644\nindex e69de29..0000000\n"}, "deleted", false},
		{"not reviewed", on, FileDiff{Path: "a.go", Deleted: true, NotReviewed: "too large", Patch: plain.Patch}, "deleted", false},
		{"not reviewed without hunk", on, FileDiff{Path: "a.go", Deleted: true, NotReviewed: "too large", Patch: "diff --git a/a.go b/a.go\ndeleted file mode 100644\n"}, "deleted", false},
		{"vendored", on, deletedWith("vendor/x.go", "-package x\n"), "vendored", true},
		{"lockfile", on, deletedWith("go.sum", "-x\n"), "lockfile", true},
		{"generated by gitattributes", on, deletedWith("gen/a.go", "-package a\n"), "generated", true},
		{"generated header on removed line 1", on, headerAt(1), "generated", true},
		{"generated header on removed line 10", on, headerAt(10), "generated", true},
		{"generated header on removed line 11", on, headerAt(11), "", false},
		{"generated header, base has none", onAtBaseFalse, headerAt(1), "", false},
		{"generated header, base has it", onAtBaseTrue, headerAt(1), "generated", true},
		{"generated header, no base check", on, headerAt(1), "generated", true},
		{"generated header, switch off", off, headerAt(1), "deleted", false},
		{"text file, switch off", off, plain, "deleted", false},
		{"modified file, header only in removed line", on, FileDiff{Path: "a.go", Patch: "diff --git a/a.go b/a.go\n--- a/a.go\n+++ b/a.go\n@@ -1 +1 @@\n-" + gen + "\n+x\n"}, "", false},
		{"removed header in a hunk starting at old line 2", on, FileDiff{Path: "a.go", Deleted: true, Patch: "diff --git a/a.go b/a.go\ndeleted file mode 100644\n--- a/a.go\n+++ /dev/null\n@@ -2,1 +0,0 @@\n-" + gen + "\n"}, "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rule, opt := tt.c.Exclusion(tt.f)
			if rule != tt.wantRule || opt != tt.wantOpt {
				t.Errorf("Exclusion() = (%q, %v), want (%q, %v)", rule, opt, tt.wantRule, tt.wantOpt)
			}
		})
	}
}

// A deleted file the read rules deny stays "deleted"; DeniedDeleted touches
// nothing else.
func TestExclusion_DeniedDeleted(t *testing.T) {
	c := NewClassifierFrom(nil, nil)
	c.ReviewDeleted = true
	c.DeniedDeleted = func(p string) bool { return strings.HasSuffix(p, ".env") }
	del := func(p string) FileDiff {
		return FileDiff{Path: p, Deleted: true, Patch: "diff --git a/" + p + " b/" + p + "\ndeleted file mode 100644\n--- a/" + p + "\n+++ /dev/null\n@@ -1 +0,0 @@\n-A=1\n"}
	}
	if rule, opt := c.Exclusion(del("prod.env")); rule != "deleted" || opt {
		t.Errorf("denied deletion: (%q, %v), want (\"deleted\", false)", rule, opt)
	}
	if rule, _ := c.Exclusion(del("a.go")); rule != "" {
		t.Errorf("allowed deletion: %q, want \"\"", rule)
	}
	if rule, _ := c.Exclusion(FileDiff{Path: "prod.env", Patch: patchWithHunk("prod.env", "A=1")}); rule != "" {
		t.Errorf("changed denied file: %q, want \"\" (not a deletion)", rule)
	}
}

